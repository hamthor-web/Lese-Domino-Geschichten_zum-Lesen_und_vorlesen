'use strict';
const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const storage = new Map();
const localStorage = {getItem: k => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,String(v)), removeItem: k => storage.delete(k)};
function visit(path, script = 'shared/progress.js') {
  const location = new URL('https://example.test/game/' + path);
  const history = {state: null, replaceState(s) {this.state=s;}, pushState(s) {this.state=s;}};
  const events = {};
  const context = {window: {}, localStorage, history, location, URL, URLSearchParams, Event, dispatchEvent() {}, addEventListener: (name,fn) => {events[name]=fn;}};
  vm.runInNewContext(readFileSync(script, 'utf8'), context);
  return {progress: context.window.SilvanaProgress || context.window.EicheProgress, events};
}
let {progress:p} = visit('vorschau-einfuehrung/?neu=1');
p.connect(0, () => assert.fail('Fresh game must not restore'));
p.finish(1);
p.checkpoint(2);
assert.equal(visit('silvana/').progress.resumeTarget(), '../vorschau-einfuehrung/?fortsetzen=1');
p = visit('vorschau-einfuehrung/?fortsetzen=1').progress;
let restored;
assert.equal(p.connect(0, s => restored=s), true);
assert.equal(restored, 2);
p = visit('szene-4/').progress;
p.connect(1, () => {});
p.checkpoint(3);
assert.equal(visit('silvana/').progress.resumeTarget(), '../szene-4/?fortsetzen=1');
p = visit('szene-4/?fortsetzen=1').progress;
assert.equal(p.connect(1, s => restored=s), true);
assert.equal(restored, 3);
const fresh = visit('vorschau-einfuehrung/?neu=1').progress;
assert.equal(fresh.connect(0, () => assert.fail('Fresh game restored')), false);
assert.equal(fresh.completed().includes(1), true);
const reset = visit('silvana/').progress;
reset.reset();
assert.equal(reset.resumeTarget(), null);
assert.equal(reset.completed().length, 0);
fresh.checkpoint(1);
assert.equal(reset.resumeTarget(), null);

let oak = visit('die-eiche/abschnitt-1/', 'die-eiche/spielstand.js').progress;
oak.save(1, {step: 6}); oak.complete(1);
oak = visit('die-eiche/abschnitt-2/', 'die-eiche/spielstand.js').progress;
oak.save(2, {screen:'game', pageIndex:1});
assert.equal(oak.latest(), 2);
assert.equal(oak.readForVisit(2).pageIndex, 1);
const oakFresh = visit('die-eiche/abschnitt-1/?neu=1','die-eiche/spielstand.js').progress;
assert.equal(oakFresh.readForVisit(1), null);
assert.equal(oakFresh.secondUnlocked(), true);
oakFresh.save(1, {step:0});
assert.equal(oakFresh.latest(), 1);
const spring = visit('die-eiche/abschnitt-5/', 'die-eiche/spielstand.js').progress;
spring.save(5, {page: 8, found: [2]});
assert.equal(visit('die-eiche/', 'die-eiche/spielstand.js').progress.latest(), 5);
assert.deepEqual(Array.from(spring.readForVisit(5).found), [2]);
assert.equal(visit('die-eiche/abschnitt-5/?neu=1', 'die-eiche/spielstand.js').progress.readForVisit(5), null);
oakFresh.reset();
assert.equal(spring.readForVisit(5), null);
assert.equal(oakFresh.latest(), null);
assert.equal(oakFresh.secondUnlocked(), false);
oak.save(2, {screen:'game'});
assert.equal(oakFresh.latest(), null);
